"""Escriba una función recursiva para calcular la operación de la potencia."""

def pot_recursiva(base, n):
    if n < 0:
        return 1 / pot_recursiva(base, -n) # exponentes negativos
    if n == 0:
        return 1 #exponente igual a 0 el resultado es 1
    return base * pot_recursiva(base, n - 1) # establecemos la condicion recursiva

