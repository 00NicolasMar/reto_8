"""Realice pruebas para calcular fibonacci con iteración o con recursión. Determine desde que número de la serie la diferencia de tiempo se vuelve significativa."""

import time

def fibonacci_recursivo(n):
    if n <= 1:
        return n
    return fibonacci_recursivo(n-1) + fibonacci_recursivo(n-2)

def fibonacci_iterativo(n):
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a

diferencia_significativa = None

for n in range(30, 41):  # reducimos el rango
    # Medimos el tiempo recursivo
    start_time = time.time()
    fibonacci_recursivo(n)
    end_time = time.time()
    timer_recursivo = end_time - start_time

    # Medimos el tiempo iterativo
    start_time = time.time()
    fibonacci_iterativo(n)
    end_time = time.time()
    timer_iterativo = end_time - start_time

    diferencia = timer_recursivo - timer_iterativo
    print("n = " + str(n) + " Recursivo: " + str(timer_recursivo) + " seg, Iterativo: " + str(timer_iterativo) + " seg, Diferencia: " + str(diferencia) + " seg")

    if not diferencia_significativa and diferencia > 0:
      diferencia_significativa = n

if diferencia_significativa:
    print("La diferencia de tiempo se vuelve significativa a partir de " + str(diferencia_significativa))
else:
    print("No se encontró una diferencia significativa.")